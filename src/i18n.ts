import { create } from 'zustand';
import { persist } from 'zustand/middleware';

export type Lang = 'th' | 'en';

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>()(
  persist((set) => ({ lang: 'th', setLang: (lang) => set({ lang }) }), { name: 'ov.lang.v1' }),
);

/** Translate an English UI string. Unknown strings fall back to English. */
export function t(en: string): string {
  const k = en.replace(/\s+/g, ' ').trim();
  if (useLang.getState().lang === 'en') return k;
  return TH[k] ?? k;
}

